  const progress = Math.min(100, Math.max(30, Math.floor(Math.sin(idx * 0.4) * 35 + 65)));
  const level = progress >= 85 ? 4 : progress >= 70 ? 3 : progress >= 50 ? 2 : progress >= 30 ? 1 : 0;
